export type LessonFormat =
  | "Квиз"
  | "Карточки"
  | "Блиц"
  | "Задачи"
  | "Чтение"
  | "Письмо"
  | "Говорение"
  | "Аудирование";

export type LessonQuestion = {
  id: string;
  prompt: string;
  options?: string[];
  correct?: number;
  answers?: string[];
  answer?: string;
  explanation?: string;
  example?: string;
};

export type Module = {
  id: string;
  title: string;
  lessons: string[]; // IDs занятий
  vocabSetId?: string; // Привязанный словарь Lexis Lab
};

export type Set = {
  id: string;
  month: string;
  title: string;
  modules: Module[];
};

export type Lesson = {
  id: string;
  title: string;
  topic: string;
  format: LessonFormat;
  level: "A1" | "A2" | "B1" | "B2" | "C1" | "ЕГЭ" | "Олимпиада";
  duration: number;
  description: string;
  code: string;
  source: "ФИПИ 2026" | "British Council B1-B2" | "Авторская подборка";
  passage?: string;
  instruction?: string;
  questions: LessonQuestion[];
};

